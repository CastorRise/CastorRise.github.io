export function localizedPath(locale: Locale, path: string): string {
  return locale === 'en' ? path : '/' + locale + (path === '/' ? '/' : path);
}

export function pagePath(path: string): string {
  return path.replace(/^\/(zh-tw|zh|ja)(?=\/|$)/, '').replace(/\/$/, '') || '/';
}
